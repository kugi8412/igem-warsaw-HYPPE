"""ComBat target per (orthogroup, SAMPLE), keyed by that sample's description.

The existing target is the mean over the samples of a (genome, category)
cell: 65 cells and seven distinct description vectors per genome, so the
conditioning channel carries seven values and "the model tells experiments
apart" has no falsifier.

Measured on `data/sample_text_emb.npz` (1487 samples, SapBERT, `condition` +
`study_title`), 1014 raw `condition` strings normalise to 482 texts and 481
vectors -- exactly one encoder collision in 482. Distinct vectors per genome
come to a median of 23 (citrinoviride 8, P1 12, reesei 117) against seven
everywhere today, and that is the number that counts: a description belongs
to one genome, so "481 against 7" misleads. The gain within a strain is 7 to
23 at the median, 7 to 12 for P1. Samples per vector: median 3.0, max 121;
mean cosine between different descriptions 0.4840.

Two variances are easy to confuse. `log_var` (beta-NLL) learns from the
residual `y - mu`, so it works unchanged at n = 1 and is the model's own
prediction spread. `log_sigma_obs` regresses a MEASURED sigma and needs a
replicate. This module therefore supplies sigma only where the description
group has n >= 2 within its own genome, and masks elsewhere, exactly as
`build_targets` does with `min_obs`. The relevant replicate fraction is 77.9 %
within the genome rather than the 89.0 % global one, and the share of rows
that actually carry a sigma target is lower still at 48.6 %, because sigma is
computed per (orthogroup, genome, vector) and is lost wherever fewer than two
columns of the group are measured in that orthogroup.

This module does not group. Grouping by category, cluster or subcategory is a
readout at the output and costs zero parameters, because the column is
generated by one shared projection; building the target and grouping it are
different operations.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Mapping, Optional, Sequence, Tuple

import numpy as np

__all__ = ["PerSampleTargets", "build_per_sample"]


@dataclass
class PerSampleDraw:
    """One draw: a single sample per row of the batch."""

    mu: np.ndarray           # [B] ComBat value of this (orthogroup, sample)
    valid: np.ndarray        # [B] bool -- is the cell measured
    text_row: np.ndarray     # [B] row index into the description matrix
    sigma: np.ndarray        # [B] sd over the group's replicates, NaN if n < 2
    sigma_valid: np.ndarray  # [B] bool
    sample_col: np.ndarray   # [B] the sample's column in the ComBat matrix


class PerSampleTargets(object):
    """The ComBat matrix plus a sample index, drawing one sample per row.

    The matrix is 11 323 x 2332 float32, about 105 MB, and is never copied on
    a draw: :meth:`draw` indexes rather than slices.
    """

    def __init__(self, og_ids: Sequence[str], sample_ids: Sequence[str],
                 matrix: np.ndarray,
                 genome_of: Mapping[str, str],
                 text_row_of: Mapping[str, int],
                 text_group_of: Mapping[str, int],
                 vectors: Optional[np.ndarray] = None) -> None:
        self.og_ids = list(og_ids)
        self.sample_ids = list(sample_ids)
        self.matrix = matrix
        self.og_index = {o: i for i, o in enumerate(self.og_ids)}
        # The description matrix lives here rather than separately, because
        # `text_row` indexes it: if the two drifted apart, the column would be
        # generated from a different sample's description than the target.
        self.vectors = (None if vectors is None
                        else np.asarray(vectors, dtype=np.float32))
        self.dim = 0 if self.vectors is None else int(self.vectors.shape[1])
        # Sample columns grouped per genome: a draw must pick a sample of THIS
        # genome, or the target describes another organism.
        self.by_genome: Dict[str, np.ndarray] = {}
        self.text_row: Dict[str, int] = dict(text_row_of)
        self.text_group: Dict[str, int] = dict(text_group_of)
        cols: Dict[str, List[int]] = {}
        for j, sid in enumerate(self.sample_ids):
            g = genome_of.get(sid)
            if g is None or sid not in self.text_row:
                continue
            cols.setdefault(g, []).append(j)
        for g, v in cols.items():
            self.by_genome[g] = np.asarray(sorted(v), dtype=np.int64)

        # sigma per (genome, description group): sd over replicates, once.
        self._sigma: Dict[Tuple[str, int], np.ndarray] = {}
        self._n_rep: Dict[Tuple[str, int], int] = {}
        for g, js in self.by_genome.items():
            grp: Dict[int, List[int]] = {}
            for j in js.tolist():
                grp.setdefault(self.text_group[self.sample_ids[j]],
                               []).append(j)
            for k, members in grp.items():
                self._n_rep[(g, k)] = len(members)
                if len(members) < 2:
                    continue
                sub = self.matrix[:, np.asarray(members, dtype=np.int64)]
                with np.errstate(invalid="ignore"):
                    self._sigma[(g, k)] = np.nanstd(sub, axis=1, ddof=1)

    # Drawing
    def draw(self, og: Sequence[str], genome: Sequence[str],
             rng: np.random.Generator) -> PerSampleDraw:
        """One sample per row, drawn UNIFORMLY within the genome.

        Uniformly rather than in proportion to sample count: reesei has 409
        samples against citrinoviride's 11, so count-weighting would give it
        37x the description exposure. Uniformity holds within a genome only,
        which leaves exposure uneven between genomes on purpose -- a corpus
        row is already (orthogroup, genome), so the corpus fixes that, not
        this sampler.
        """
        n = len(og)
        mu = np.full(n, np.nan, dtype=np.float32)
        tr = np.zeros(n, dtype=np.int64)
        sg = np.full(n, np.nan, dtype=np.float32)
        sc = np.full(n, -1, dtype=np.int64)
        for i in range(n):
            js = self.by_genome.get(str(genome[i]))
            oi = self.og_index.get(str(og[i]))
            if js is None or js.size == 0 or oi is None:
                continue
            j = int(js[rng.integers(js.size)])
            sid = self.sample_ids[j]
            sc[i] = j
            tr[i] = int(self.text_row[sid])
            mu[i] = self.matrix[oi, j]
            s = self._sigma.get((str(genome[i]), self.text_group[sid]))
            if s is not None:
                sg[i] = s[oi]
        valid = np.isfinite(mu)
        svalid = valid & np.isfinite(sg)
        return PerSampleDraw(mu=mu, valid=valid, text_row=tr, sigma=sg,
                             sigma_valid=svalid, sample_col=sc)

    # Falsifiers
    def category_centroids(self, category_of: Mapping[str, int],
                           n_cat: int) -> Optional[np.ndarray]:
        """[K, d_lm] -- the mean description of the samples in category k.

        Needed even though category prototypes exist, because a column
        readout from a prototype is an out-of-distribution input to
        `text_proj`, which in the per-sample regime has only ever seen sample
        descriptions. Mean cosine is +0.5041 among sample descriptions,
        -0.1619 among prototypes and +0.0103 between the two sets, all of norm
        1, so the prototypes are near-orthogonal to the description cloud. The
        general rule: any grouping must take the group's description from the
        distribution the model was trained on, and a hand-written prototype is
        not from it.
        """
        if self.vectors is None:
            return None
        acc = [[] for _ in range(int(n_cat))]
        for sid, r in self.text_row.items():
            k = category_of.get(sid)
            if k is None or not 0 <= int(k) < int(n_cat):
                continue
            acc[int(k)].append(self.vectors[int(r)])
        out = np.zeros((int(n_cat), self.dim), dtype=np.float32)
        ok = 0
        for k, v in enumerate(acc):
            if v:
                out[k] = np.mean(v, axis=0)
                ok += 1
        # A category with no samples stays the zero vector rather than a
        # prototype: substituting one would silently reintroduce, for some
        # columns, the out-of-distribution input this method removes.
        self._n_cent = ok
        return out

    def gather(self, rows: np.ndarray) -> np.ndarray:
        """[B, d_lm] description vectors for the given rows; -1 gives zeros.

        Zeros rather than a stand-in vector: a row with no description must
        reach `unknown_token_text` through the `text_ok` mask, applied to the
        operand. Anything else here becomes a learned constant reported as a
        channel share -- the failure this corpus already had on the flanks.
        """
        if self.vectors is None:
            raise ValueError("PerSampleTargets built without vectors")
        r = np.asarray(rows, dtype=np.int64)
        out = np.zeros((r.size, self.dim), dtype=np.float32)
        ok = r >= 0
        if ok.any():
            out[ok] = self.vectors[r[ok]]
        return out

    def report(self) -> Dict[str, object]:
        n_g = {g: int(v.size) for g, v in self.by_genome.items()}
        grup = {}
        for g, js in self.by_genome.items():
            grup[g] = len({self.text_group[self.sample_ids[j]]
                           for j in js.tolist()})
        rep = sorted(self._n_rep.values())
        z2 = sum(v for v in rep if v >= 2)
        # The key names matter, because three different numbers describe
        # "replication" and confusing them gives three different conclusions:
        # 481 distinct description VECTORS in the corpus; 646 (genome, vector)
        # CELLS, since one description occurs in more than one genome and
        # sigma must be computed within a genome; and 0.779, the fraction of
        # samples with a replicate IN THEIR OWN genome (0.890 globally). None
        # of these is the share of ROWS carrying a sigma target, which is
        # 48.6 % -- see the module docstring.
        return {
            "n_og": len(self.og_ids),
            "n_samples": sum(n_g.values()),
            "n_genomes": len(n_g),
            "opisow_na_genom_mediana": int(np.median(list(grup.values()))),
            "opisow_na_genom_min": int(min(grup.values())),
            "opisow_na_genom_max": int(max(grup.values())),
            "komorek_genom_x_opis": len(rep),
            "frakcja_probek_z_replika_W_GENOMIE": (
                float(z2) / max(sum(rep), 1)),
            "komorek_z_sigma": len(self._sigma),
        }


def build_per_sample(combat_path: str, samples, text_cache_path: str
                     ) -> PerSampleTargets:
    """Build from the ComBat matrix and a SAMPLE-keyed description artefact.

    Refuses a cell-keyed artefact: a `<genome>|<category>` key instead of a
    sample id means every sample of a genome receives the same vector, so the
    per-sample regime would be the per-cell regime under another name -- a
    failure that looks exactly like a working channel.
    """
    from .labels import read_matrix

    og_ids, cols, mat = read_matrix(combat_path)
    z = np.load(text_cache_path, allow_pickle=True)
    keys = [str(k) for k in z["keys"]]
    vecs = np.asarray(z["vectors"], dtype=np.float32)
    if any("|" in k for k in keys[:50]):
        raise ValueError(
            "%s is keyed by CELL (<genome>|<category>), not by sample: the "
            "first keys are %r. Every sample of a genome would receive the "
            "same vector and the per-sample regime would be the per-cell "
            "regime under another name -- refused rather than run."
            % (text_cache_path, keys[:3]))

    text_row = {k: i for i, k in enumerate(keys)}
    # A description group is vector identity, not text identity: the vector
    # is what reaches the model, and the one measured encoder collision in
    # 482 joins two texts into one group for sigma as well.
    sig = {}
    group = {}
    for k, i in text_row.items():
        s = vecs[i].tobytes()
        group[k] = sig.setdefault(s, len(sig))

    genome_of = {}
    for sid, gen, keep in zip(samples.sample_ids, samples.genome,
                              samples.keep):
        if keep:
            genome_of[sid] = gen
    out = PerSampleTargets(og_ids, cols, mat, genome_of, text_row, group,
                           vectors=vecs)
    # Category centroids, computed once here: `evaluate` needs them every
    # epoch and they depend only on the artefact and the category assignment.
    import numpy as _np
    cat = _np.asarray(samples.category)
    kmap = {}
    if cat.ndim == 2:
        for sid, row, keep in zip(samples.sample_ids, cat, samples.keep):
            if not keep:
                continue
            w = _np.flatnonzero(_np.asarray(row) > 0.5)
            if w.size:
                # The first bit set. A multi-category sample goes into one
                # group -- an assumption, not a fact about the data.
                kmap[sid] = int(w[0])
        out.cat_centroids = out.category_centroids(kmap, int(cat.shape[1]))
        out.n_centroids = int(getattr(out, "_n_cent", 0))
    else:
        out.cat_centroids = None
        out.n_centroids = 0
    return out
